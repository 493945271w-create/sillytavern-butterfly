import { completeJson, readSettings, cleanSettings, readKey } from './api.mjs';
import { nativeResearch, researchQueries } from './native.mjs';
import { butterflyInstructions, butterflySchema, prepareButterflyInput } from './analysis.mjs';
import { selectionInstructions, selectionSchema } from './selection.mjs';
import { attachSources, prepareReferences } from './references.mjs';

export async function requestAnalysis(input, signal, context, options = {}) {
    const sources = prepareReferences(input.sources || []);
    const settings = cleanSettings(readSettings(context));
    const requestOptions = { ...options, settings, key: options.key ?? readKey(settings.url) };
    const prepared = { ...prepareButterflyInput(input), sources };
    const result = await completeJson(context, butterflyInstructions, butterflySchema, prepared, signal, requestOptions);
    if (!settings.search) return attachSources(result, sources);
    const queries = researchQueries(result);
    if (!queries.length) return attachSources(result, sources);
    options.progress?.('正在用所选模型的原生联网工具核对原著…');
    const research = await nativeResearch(settings, requestOptions.key, queries.slice(0, 3), { signal, fetchImpl: options.fetchImpl });
    if (signal?.aborted) throw new DOMException('已取消', 'AbortError');
    options.progress?.('已收到搜索来源，正在核对剧情分歧与资料引文…');
    const corpus = [...sources, ...research.sources];
    const checked = await completeJson(context, butterflyInstructions, butterflySchema,
        { ...prepared, sources: corpus, researchQuestions: queries.slice(0, 3) }, signal, requestOptions);
    // Preserve only adapter-owned sources. JSON generated by the model cannot add evidence.
    const { sources: _ignoredSources, searches: _ignoredSearches, ...content } = checked;
    if (queries.length > 3 && Array.isArray(content.notes)) content.notes = [...content.notes.slice(0, 7), '本批仅搜索前三个原著问题，其余缺少依据的候选仍待核实。'];
    return { ...content, sources: corpus, searches: research.searches };
}
export async function requestSelection(input, signal, context) {
    const sources = prepareReferences(input.sources || []);
    const result = await completeJson(context, selectionInstructions, selectionSchema, { ...input, sources }, signal);
    return attachSources(result, sources);
}
